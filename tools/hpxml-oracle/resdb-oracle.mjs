#!/usr/bin/env node
/**
 * Oracle values for RHOE.infiltration.resdb_ach50 (WO-03 B8).
 *
 *   node tools/hpxml-oracle/resdb-oracle.mjs [--out <work dir>]
 *
 * For each committed calc fixture and each leakiness description, takes the fixture's serialized
 * HPXML, replaces the blower-door measurement with LeakinessDescription (the oracle's no-test
 * path), runs the pinned oracle design-only, and reads back the ACH50 the oracle defaulted in
 * in.xml. Writes packages/calc/fixtures/oracle/resdb-ach50.json with the RhoeFlow inputs for
 * each case, so the unit test compares RhoeFlow's regression with the oracle's own.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CalcFixtureSchema, prepareInput, resdbInputFromAssessment, resolveWeatherStation } from "@rhoeflow/calc";
import { assessmentToHpxml } from "@rhoeflow/hpxml";
import { oracleEnv, runDesignOnly } from "./oracle.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const fixturesDir = join(repo, "packages/calc/fixtures");
const outFlag = process.argv.indexOf("--out");
const work = resolve(outFlag >= 0 ? process.argv[outFlag + 1] : join(tmpdir(), "rhoe-resdb"));

const env = oracleEnv();
console.log(`oracle: OpenStudio ${env.version}, OpenStudio-HPXML ${env.hpxmlVersion}; work ${work}`);
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });

const LEVELS = ["very tight", "tight", "average", "leaky", "very leaky"];
const cases = [];
for (const file of readdirSync(fixturesDir).filter((f) => f.endsWith(".fixture.json")).sort()) {
  const fx = CalcFixtureSchema.parse(JSON.parse(readFileSync(join(fixturesDir, file), "utf8")));
  const prepared = prepareInput(fx.input);
  if (!prepared.ok) throw new Error(`${fx.name} does not prepare`);
  const station = resolveWeatherStation(prepared.input.weather);
  const xml = assessmentToHpxml(prepared.input.assessment, { epwFile: station.epwFile, stateCode: station.state });
  for (const level of LEVELS) {
    // Drop the blower-door method declaration too, or the oracle demands a measured leakage.
    const variant = xml.replace(/\s*<InfiltrationMethod>blower door<\/InfiltrationMethod>/, "").replace(/<AirInfiltrationMeasurement>([\s\S]*?)<\/AirInfiltrationMeasurement>/, (_m, inner) => {
      let s = inner.replace(/\s*<HousePressure>[^<]*<\/HousePressure>/, "").replace(/\s*<BuildingAirLeakage>[\s\S]*?<\/BuildingAirLeakage>/, "");
      s = s.replace(/(\s*)<InfiltrationVolume>/, `$1<LeakinessDescription>${level}</LeakinessDescription>$1<InfiltrationVolume>`);
      if (!s.includes("LeakinessDescription")) throw new Error(`${fx.name}: could not place LeakinessDescription`);
      return `<AirInfiltrationMeasurement>${s}</AirInfiltrationMeasurement>`;
    });
    const tag = `${fx.name}-${level.replace(" ", "-")}`;
    const input = join(work, `${tag}.xml`);
    writeFileSync(input, variant);
    const run = runDesignOnly(input, join(work, tag), { quiet: true });
    if (run.status !== 0) throw new Error(`${tag}: oracle exit ${run.status}: ${run.error}`);
    const inXml = readFileSync(join(run.runDir, "in.xml"), "utf8");
    const m = /<AirInfiltrationMeasurement>[\s\S]*?<AirLeakage[^>]*>([^<]+)<\/AirLeakage>/.exec(inXml);
    if (!m) throw new Error(`${tag}: no defaulted AirLeakage in in.xml`);
    const oracleAch50 = Number(m[1]);
    // With a leakiness description the oracle also defaults ManualJ InfiltrationMethod to the
    // default infiltration table, so the same run checks MJ8.infiltration.tightness_class.
    const method = /<InfiltrationMethod[^>]*>([^<]+)<\/InfiltrationMethod>/.exec(inXml)?.[1] ?? null;
    const details = JSON.stringify(JSON.parse(readFileSync(join(run.runDir, "results_design_load_details.json"), "utf8")));
    const cfm = /"Infiltration":\{"Heating CFM":([\d.]+),"Cooling CFM":([\d.]+)\}/.exec(details);
    cases.push({
      fixture: fx.name,
      leakiness: level,
      oracle_ach50: oracleAch50,
      oracle_infiltration_method: method,
      oracle_infiltration_cfm: cfm ? { heating: Number(cfm[1]), cooling: Number(cfm[2]) } : null,
      input: resdbInputFromAssessment(prepared.input.assessment, level),
    });
    console.log(`${tag.padEnd(44)} oracle ACH50 ${oracleAch50}`);
  }
}

const out = {
  $comment:
    "Oracle ACH50 for the LeakinessDescription path (OpenStudio-HPXML v1.12.0 defaults.rb get_infiltration_ach50), one case per committed fixture and leakiness level, with the design infiltration cfm of the oracle default-infiltration-table path (rounded to 1 cfm by the oracle). Generated by tools/hpxml-oracle/resdb-oracle.mjs; in.xml carries the full-precision value.",
  oracle: { openstudio: env.version, openstudio_hpxml: env.hpxmlVersion },
  cases,
};
const outFile = join(fixturesDir, "oracle/resdb-ach50.json");
writeFileSync(outFile, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${outFile} (${cases.length} cases)`);
