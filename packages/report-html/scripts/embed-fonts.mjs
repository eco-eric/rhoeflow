// Regenerates src/fonts.generated.ts from the font files in ../fonts (ADR-037: the PDF embeds its
// font, so Browser Run and CI's Chromium draw the same glyphs). Run with `pnpm --filter
// @rhoeflow/report-html fonts` after replacing a font file; test/fonts.test.ts fails until you do.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const here = import.meta.dirname;
const files = ["geist-latin.woff2", "geist-latin-ext.woff2", "geist-mono-latin.woff2", "geist-mono-latin-ext.woff2"];
const lines = [
  "// Generated by scripts/embed-fonts.mjs from ../fonts. Do not edit by hand.",
  "// Geist and Geist Mono, SIL Open Font License 1.1 (fonts/OFL.txt).",
  "export const FONT_FILES: Readonly<Record<string, { sha256: string; base64: string }>> = {",
];
for (const f of files) {
  const bytes = readFileSync(resolve(here, "../fonts", f));
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  lines.push(`  ${JSON.stringify(f)}: { sha256: ${JSON.stringify(sha256)}, base64: ${JSON.stringify(bytes.toString("base64"))} },`);
}
lines.push("};", "");
writeFileSync(resolve(here, "../src/fonts.generated.ts"), lines.join("\n"));
console.log(`wrote src/fonts.generated.ts (${files.length} fonts)`);
